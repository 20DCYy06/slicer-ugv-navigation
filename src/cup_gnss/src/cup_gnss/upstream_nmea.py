"""NMEA 0.6.1 reuse with this rover's explicit timing/quality contract.

The two sibling _nmea_0_6_1 modules are unmodified BSD upstream source, locked
by NMEA_UPSTREAM.json. They keep offline tools independent of rospy. ROS live
fixes are generated by the same released RosNMEADriver, captured without its
extra publishers or parameter-server defaults. No second serial owner exists.

Project-only adaptations: bound malformed fields, support equivalent modern
talker IDs, preserve quality/differential-age metadata, retain receipt stamps
and UNKNOWN covariance. Upstream's guessed GGA date and default quality EPE
are deliberately not promoted into measurement time or measured uncertainty.
"""
import copy
import functools
import math
import operator
import re

from . import _nmea_0_6_1_checksum as checksum
from . import _nmea_0_6_1_parser as parser

BACKEND = 'nmea_navsat_driver/0.6.1'


def _number(value, nonnegative=False):
    try:
        result = float(value)
    except (ValueError, TypeError, OverflowError):
        return None
    return result if math.isfinite(result) and (not nonnegative or result >= 0) else None


def _integer(value):
    return int(value) if isinstance(value, str) and re.fullmatch(r'\d+', value) else None


def _epoch(value):
    # A GGA has no date. Only a bounded time-of-day is used for stream ordering.
    if not re.fullmatch(r'\d{6}(?:\.\d+)?', value):
        return None
    hour, minute, second = int(value[:2]), int(value[2:4]), float(value[4:])
    if hour >= 24 or minute >= 60 or second >= 60:
        return None
    return hour * 3600 + minute * 60 + second


def upstream_sentence(raw):
    """Parser projection only; never replaces recorded/raw NTRIP input bytes.

    Release 0.6.1 restricts its regex to GP/GN/GL/IN. Field layouts for other
    standard talkers are identical. Normalize that envelope only; preserve
    original talker, checksum and raw sentence in the public parsed record.
    """
    if raw.startswith('$') and raw[1:3] in ('GP', 'GN', 'GL', 'IN'):
        return raw
    body = 'GP' + raw[3:raw.rfind('*')]
    value = functools.reduce(operator.xor, body.encode('ascii'), 0)
    return '${}*{:02X}'.format(body, value)


def _coordinate(fields, data, name, index, direction_index, latitude):
    value, direction = fields[index], fields[direction_index]
    digits, limit = (2, 90) if latitude else (3, 180)
    if direction not in (('N','S') if latitude else ('E','W')):
        return None
    if not re.fullmatch(r'\d{' + str(digits + 2) + r'}(?:\.\d+)?', value):
        return None
    # The upstream parser performs degree conversion; this guard rejects minute
    # overflow and invalid pole/antimeridian values it otherwise accepts.
    if float(value[digits:]) >= 60:
        return None
    converted = _number(data.get(name))
    if converted is None or converted > limit:
        return None
    return -converted if direction in ('S','W') else converted


def parse_nmea(raw):
    """Existing record-dict interface, backed by the locked upstream library."""
    if not isinstance(raw, str) or len(raw) > 1024:
        return None
    match = re.fullmatch(r'([!$])([\x20-\x7e]+)\*([0-9A-Fa-f]{2})', raw)
    if not match or not checksum.check_nmea_checksum(raw):
        return None
    fields = match.group(2).split(',')
    if not re.fullmatch(r'[A-Z0-9]{5}', fields[0]):
        return None
    record = {'raw':raw, 'sentence_id':fields[0], 'talker':fields[0][:2],
              'kind':fields[0][2:], 'parser_backend':BACKEND,
              'stamp_semantics':'receipt; GGA time-of-day has no date'}
    kind = record['kind']
    if (kind == 'GGA' and len(fields) < 15) or (kind == 'RMC' and len(fields) < 10) or (kind == 'GST' and len(fields) < 9):
        return None
    if kind not in parser.parse_maps:
        return record  # Preserve checksum-valid receiver sentences we do not use.
    try:
        parsed = parser.parse_nmea_sentence(upstream_sentence(raw))
    except (ValueError, IndexError, TypeError, OverflowError) as error:
        # A malformed measurement can remain diagnostic evidence but cannot
        # acquire valid coordinates from a partly parsed dictionary.
        parsed = {}
        record['upstream_parse_error'] = type(error).__name__
    data = parsed.get(kind, {}) if isinstance(parsed, dict) else {}
    if kind == 'GGA':
        altitude = _number(data.get('altitude')) if fields[10] == 'M' else None
        geoid = _number(data.get('mean_sea_level')) if fields[12] == 'M' else None
        record.update({
            'utc_time':fields[1], 'epoch':_epoch(fields[1]),
            'latitude':_coordinate(fields,data,'latitude',2,3,True),
            'longitude':_coordinate(fields,data,'longitude',4,5,False),
            'quality':_integer(fields[6]), 'satellites':_integer(fields[7]),
            'hdop':_number(data.get('hdop'),True), 'altitude_msl':altitude,
            'geoid_separation':geoid,
            'altitude':_number(altitude+geoid) if altitude is not None and geoid is not None else None,
            'differential_age_s':_number(fields[13],True), 'station_id':fields[14],
        })
    elif kind == 'RMC':
        record.update({'utc_time':fields[1], 'epoch':_epoch(fields[1]),
                       'status':fields[2], 'mode':fields[12] if len(fields)>12 else '',
                       'navigation_status':fields[13] if len(fields)>13 else '',
                       'rmc_date':fields[9]})
    elif kind == 'GST':
        # Preserve genuine receiver uncertainty as source data. We do not invent
        # a time association to a GGA or reuse upstream default EPE as measured.
        record.update(utc_time=fields[1], epoch=_epoch(fields[1]))
        record['receiver_error_fields'] = {key:_number(value) for key,value in data.items()
                                          if key.endswith('_std_dev')}
        record['covariance_source'] = 'receiver GST; not associated to a GGA'
    return record


class _Capture:
    def __init__(self):
        self.messages = []

    def publish(self, message):
        self.messages.append(copy.deepcopy(message))


class NmeaFixAdapter:
    """Upstream standard-message generation without ROS publishers/ROS params.

    Its __init__ creates four extra publishers and reads quality EPE parameters;
    upstream has no dependency-injection constructor. A minimal subclass binds
    capture sinks and UNKNOWN uncertainty, then calls the unchanged public
    add_sentence method. Project freshness/quality policy remains GnssModel's.
    """
    def __init__(self):
        from libnmea_navsat_driver.driver import RosNMEADriver
        from sensor_msgs.msg import NavSatFix, NavSatStatus

        class CapturedDriver(RosNMEADriver):
            def __init__(self):
                self.fix_pub, self.vel_pub = _Capture(), _Capture()
                self.heading_pub, self.time_ref_pub = _Capture(), _Capture()
                self.use_GNSS_time, self.use_RMC = False, False
                self.time_ref_source, self.valid_fix = None, False
                self.using_receiver_epe = False
                self.lon_std_dev = self.lat_std_dev = self.alt_std_dev = float('nan')
                self.gps_qualities = {
                    quality:[float('nan'), status, NavSatFix.COVARIANCE_TYPE_UNKNOWN]
                    for quality,status in ((-1,NavSatStatus.STATUS_NO_FIX),
                                           (0,NavSatStatus.STATUS_NO_FIX),
                                           (1,NavSatStatus.STATUS_FIX),
                                           (2,NavSatStatus.STATUS_SBAS_FIX),
                                           (4,NavSatStatus.STATUS_GBAS_FIX),
                                           (5,NavSatStatus.STATUS_GBAS_FIX),
                                           (9,NavSatStatus.STATUS_GBAS_FIX))}
        self.driver = CapturedDriver()
        self.message_class = NavSatFix
        self.generated_count = 0

    def to_fix(self, raw_gga, snapshot, receipt_stamp, frame_id):
        """Generate upstream fix, then apply explicit unchanged rover policy."""
        expected = snapshot['fix']
        fix = self.message_class()
        if expected['valid']:
            parsed = parse_nmea(raw_gga)
            if parsed is None or parsed['kind'] != 'GGA' or parsed.get('epoch') is None:
                raise ValueError('Qualified fix is missing its valid original GGA')
            diagnostics = snapshot.get('diagnostics', {})
            if (parsed.get('quality') != diagnostics.get('gga_quality') or
                    parsed.get('utc_time') != diagnostics.get('gga_utc_time')):
                raise ValueError('Qualified fix and original GGA quality/epoch differ')
            self.driver.fix_pub.messages.clear()
            try:
                self.driver.add_sentence(upstream_sentence(raw_gga),frame_id,timestamp=receipt_stamp)
            except (ValueError, IndexError, TypeError, OverflowError) as error:
                raise ValueError('Upstream could not generate the qualified GGA fix') from error
            if len(self.driver.fix_pub.messages) != 1:
                raise ValueError('Upstream did not generate exactly one qualified GGA fix')
            fix = self.driver.fix_pub.messages.pop()
            self.driver.time_ref_pub.messages.clear()  # Host-inferred GGA date is not published.
            self.generated_count += 1
            for key in ('latitude','longitude'):
                if not math.isclose(getattr(fix,key),expected[key],abs_tol=1e-10,rel_tol=0):
                    raise ValueError('Upstream {} differs from admitted GGA'.format(key))
            if math.isfinite(expected['altitude']) and not math.isclose(
                    fix.altitude, expected['altitude'], abs_tol=1e-9, rel_tol=0):
                raise ValueError('Upstream ellipsoid height differs from admitted GGA')
        # Explicit compatibility boundary: validity is the existing advancing/
        # receipt/differential-age policy, not upstream's q4/q5 shared status.
        fix.header.stamp, fix.header.frame_id = receipt_stamp, frame_id
        for key in ('latitude','longitude','altitude','position_covariance','position_covariance_type'):
            setattr(fix,key,expected[key])
        fix.status.status, fix.status.service = expected['status'], expected['service']
        return fix
